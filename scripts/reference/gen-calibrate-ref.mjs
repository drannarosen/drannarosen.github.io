/*
 * gen-calibrate-ref.mjs — record what the CPU reference renderer produces, once.
 *
 * `WHITE_FROM_ANALYTIC_MEAN` stands in for a per-frame histogram pass, so the gate has to
 * check that the cheap analytic mean really tracks the rendered frame's white point across
 * everything a user can change. Getting the true white point means RASTERISING, which costs
 * ~100 seconds for the full sweep — against a 4 second build.
 *
 * That looked like a choice between a slow build and thin coverage, and it is not one: the
 * CPU reference is DETERMINISTIC. Same population, same configuration, same pixels, every
 * time. So it does not belong in the build at all. Run once, committed, and the gate then
 * compares the millisecond-scale analytic mean against recorded values — all seventeen
 * configurations, every build, in a few milliseconds.
 *
 * Same pattern as `passbandCurves.ts` and `lupton-astropy.json`: generated, committed, gated.
 *
 * WHAT MAKES IT SAFE is the fingerprint. A committed fixture's danger is that it keeps
 * certifying a calibration after the thing it measured has changed — the optics constants,
 * the PSF, the population. So the fixture records a fingerprint of exactly those inputs, and
 * the gate fails if it no longer matches, telling you to regenerate rather than quietly
 * passing against a stale reference.
 *
 * Usage:
 *   node --experimental-strip-types scripts/reference/gen-calibrate-ref.mjs
 */
import { writeFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { clusterStarTable } from "../../src/novascope/viz/starfield/source.ts";
import { prepareStarField } from "../../src/novascope/viz/starfield/prepare.ts";
import { renderReferenceLupton } from "../../src/novascope/viz/starfield/reference.ts";
import { analyticMeanIntensity, calibrationFingerprint, CALIBRATION_RUNS, floorForDepth } from "../../src/novascope/viz/starfield/calibrate.ts";

const HERE = dirname(fileURLToPath(import.meta.url));

const stars = clusterStarTable({ sampling: { mode: "count", target: 10_000 } });
const rows = [];
console.log("rasterising the CPU reference for each configuration…");
for (const run of CALIBRATION_RUNS) {
  const field = prepareStarField(stars, { ...run.prepare });
  const img = renderReferenceLupton(field, run.camera, { depthMag: run.depthMag });
  const mean = analyticMeanIntensity(field, run.camera.width, run.camera.height, {
    floor: floorForDepth(run.depthMag),
  });
  const ratio = (img.whitePixel ?? 0) / mean;
  rows.push({ id: run.id, whitePixel: img.whitePixel, analyticMean: mean, ratio });
  console.log(`  ${run.id.padEnd(16)} whitePixel ${img.whitePixel.toExponential(4)}  ratio ${ratio.toFixed(3)}`);
}

const ratios = rows.map((r) => r.ratio);
const geometricMean = Math.exp(ratios.reduce((a, b) => a + Math.log(b), 0) / ratios.length);
const min = Math.min(...ratios);
const max = Math.max(...ratios);

const out = {
  _comment:
    "GENERATED by scripts/reference/gen-calibrate-ref.mjs — do not edit by hand. " +
    "whitePixel is the 99.5th percentile of lit-pixel intensity from the CPU reference " +
    "rasteriser, which is deterministic. check:calibrate compares the fast analytic mean " +
    "against these instead of re-rasterising, so all configurations are gated on every build.",
  _staleness:
    "`fingerprint` covers every constant that determines these numbers. If the gate reports " +
    "a mismatch the fixture is STALE, not wrong — regenerate it and re-derive the constant.",
  fingerprint: calibrationFingerprint(),
  geometricMean: Number(geometricMean.toPrecision(6)),
  spread: { min: Number(min.toPrecision(6)), max: Number(max.toPrecision(6)) },
  spreadMag: Number((2.5 * Math.log10(max / min)).toPrecision(4)),
  runs: rows.map((r) => ({
    id: r.id,
    whitePixel: Number(r.whitePixel.toPrecision(10)),
    analyticMean: Number(r.analyticMean.toPrecision(10)),
    ratio: Number(r.ratio.toPrecision(6)),
  })),
};

const target = resolve(HERE, "calibrate-whitepoint.json");
writeFileSync(target, JSON.stringify(out, null, 1) + "\n");
console.log(
  `\n✓ wrote calibrate-whitepoint.json — ${rows.length} configurations, ` +
    `white/mean = ${geometricMean.toFixed(2)}, spread ${min.toFixed(2)}..${max.toFixed(2)} ` +
    `(${(2.5 * Math.log10(max / min)).toFixed(2)} mag)`,
);
