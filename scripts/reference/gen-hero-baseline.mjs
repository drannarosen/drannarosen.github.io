/*
 * gen-hero-baseline.mjs — freeze the homepage hero's output, once.
 *
 * ── WHAT IT RECORDS ──
 *
 * `ClusterHero.astro` calls `initClusterField({ canvas, reducedMotion })` with no count and no
 * seed, so `src/lib/hero/render.ts` falls back to `count: 520` and the sampler falls back to
 * `seed: 20260718`. That exact call is what this records, so the fixture is the picture that
 * actually ships rather than a configuration nobody renders.
 *
 * ── WHY IT IS A SEPARATE SCRIPT AND A SEPARATE COMMIT ──
 *
 * It runs BEFORE the hero's code is relocated, against the sampler still living in
 * `@novascope/core/imf`. `src/lib/hero/hero.test.ts` then asserts the relocated sampler
 * reproduces it. A fixture generated in the same commit as the change it certifies proves only
 * that the code agrees with itself — the trap `check:calibrate`'s fingerprint exists to close.
 *
 * ── DO NOT REGENERATE TO MAKE A FAILING TEST PASS ──
 *
 * A failure means the relocation changed the homepage, which is the one thing it must not do
 * (plan D8). Regenerating would launder that change into a new baseline and the picture would
 * silently move. Read the diff instead: the likeliest cause is a difference in how many randoms
 * `samplePlummer` consumes, since a changed draw count reshuffles every star after it.
 *
 * Usage:
 *   node --experimental-strip-types scripts/reference/gen-hero-baseline.mjs
 */
import { writeFileSync, mkdirSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { sampleCluster } from "../../src/novascope/core/imf/index.ts";

/* The homepage's own call — see `src/lib/hero/render.ts` (count) and `sampler.ts` (seed). */
const CALL = { count: 520, seed: 20260718 };

const stars = sampleCluster(CALL);

/*
 * 15 significant figures: enough that a real change cannot hide inside the rounding, and short
 * enough that the fixture is a file a person can read. A double carries ~15-17, so this keeps
 * everything meaningful and drops only the last bit or two of noise.
 */
const round = (v) => Number(v.toPrecision(15));

const out = {
  _comment:
    "GENERATED by scripts/reference/gen-hero-baseline.mjs from the PRE-RELOCATION sampler. " +
    "src/lib/hero/hero.test.ts asserts the relocated sampler reproduces it exactly. " +
    "If that test fails the relocation is wrong — DO NOT regenerate this file to make it pass.",
  call: CALL,
  count: stars.length,
  stars: stars.map((s) => ({
    x: round(s.x),
    y: round(s.y),
    z: round(s.z),
    mass: round(s.mass),
    teff: round(s.teff),
    color: s.color.map(round),
    sizePx: round(s.sizePx),
    baseOpacity: round(s.baseOpacity),
    twinkles: s.twinkles,
  })),
};

const target = resolve(
  dirname(fileURLToPath(import.meta.url)),
  "../../src/lib/hero/__fixtures__/hero-baseline.json",
);
mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, JSON.stringify(out, null, 1) + "\n");

const twinkling = stars.filter((s) => s.twinkles).length;
console.log(`✓ wrote hero-baseline.json — ${stars.length} stars, ${twinkling} twinkling`);
console.log(
  `  first (after painter sort): mass ${stars[0].mass.toPrecision(8)}  ` +
    `x ${stars[0].x.toPrecision(8)}  sizePx ${stars[0].sizePx.toPrecision(8)}`,
);
